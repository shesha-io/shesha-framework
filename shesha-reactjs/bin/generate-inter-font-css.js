#!/usr/bin/env node
/* eslint-disable no-console */

/**
 * Generates a self-contained @font-face CSS file for the Inter font from the
 * installed @fontsource-variable/inter package, inlining every referenced
 * .woff2 file as a base64 data URI.
 *
 * This exists because rollup's bundling pipeline (rollup-plugin-postcss +
 * postcss-url + @rollup/plugin-node-resolve) cannot reliably resolve this
 * package's "exports" map for a bare CSS subpath, nor inline its woff2
 * url() references when it is resolved via a workaround. Pre-generating a
 * plain, already-inlined CSS file and importing it via a normal relative
 * path sidesteps all of that: rollup just bundles ordinary CSS text, no
 * live asset resolution required.
 *
 * @fontsource-variable/inter remains the versioned source of truth. `npm run
 * build` regenerates the output file fresh every time, so the shipped dist/
 * is always in sync with whatever version is installed. The COMMITTED copy
 * of the output file only updates when someone runs this script and commits
 * the diff, so after bumping @fontsource-variable/inter's version, run:
 *   npm install
 *   npm run generate-inter-font
 * and commit the resulting change to interFont.generated.css alongside the
 * version bump - otherwise the committed file silently goes stale relative
 * to package.json even though a real `npm run build` would still be correct.
 */

const fs = require('fs');
const path = require('path');

const SOURCE_CSS = require.resolve('@fontsource-variable/inter/wght.css');
const SOURCE_DIR = path.dirname(SOURCE_CSS);
const OUTPUT_CSS = path.join(__dirname, '..', 'src', 'providers', 'theme', 'interFont.generated.css');

function inlineFontUrls(css) {
  const urlPattern = /url\(\.\/(files\/[^)]+\.woff2)\)/g;

  return css.replace(urlPattern, (match, relativePath) => {
    const fontFilePath = path.join(SOURCE_DIR, relativePath);
    const fontData = fs.readFileSync(fontFilePath);
    const base64 = fontData.toString('base64');
    return `url(data:font/woff2;base64,${base64})`;
  });
}

function normalizeLineEndings(text) {
  return text.replace(/\r\n?/g, '\n');
}

/**
 * Writes `newContent` to `filePath` only if the existing content differs.
 * If the file does not exist, it is created.
 * Returns `true` if the file was written, `false` if it was skipped.
 */
function writeIfChanged(filePath, newContent, encoding = 'utf8') {
  try {
    const existingContent = fs.readFileSync(filePath, { encoding });
    if (normalizeLineEndings(existingContent) === normalizeLineEndings(newContent)) {
      return false;
    }
  } catch (err) {
    if (err.code !== 'ENOENT') throw err;
  }

  fs.writeFileSync(filePath, newContent, { encoding });
  return true;
}

function generate() {
  try {
    console.log('Generating self-contained Inter font CSS...');

    const sourceCss = fs.readFileSync(SOURCE_CSS, 'utf8');
    const inlinedCss = inlineFontUrls(sourceCss);

    const header = '/* AUTO-GENERATED by bin/generate-inter-font-css.js from @fontsource-variable/inter. Do not edit by hand.\n'
      + '   After bumping the @fontsource-variable/inter version, re-run `npm run generate-inter-font`\n'
      + '   and commit the resulting change to this file. */\n\n';

    const updated = writeIfChanged(OUTPUT_CSS, header + inlinedCss);

    console.log(updated
      ? `Wrote self-contained font CSS to ${path.relative(process.cwd(), OUTPUT_CSS)}`
      : 'Skipped writing self-contained font CSS (no change)'
    );
  } catch (error) {
    console.error('Failed to generate Inter font CSS:');
    console.error(`   ${error.message}`);
    process.exit(1);
  }
}

generate();
